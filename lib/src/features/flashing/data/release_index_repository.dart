import 'dart:convert';

import 'package:flutter/services.dart' show rootBundle;
import 'package:logging/logging.dart';
import 'package:riverpod_annotation/riverpod_annotation.dart';
import 'package:shared_preferences/shared_preferences.dart';

import '../../../core/networking/connectivity_service.dart';
import '../../../core/networking/device_dio.dart';

part 'release_index_repository.g.dart';

final _log = Logger('ReleaseIndexRepository');

const artifactoryIndexUrl =
    'https://artifactory.expresslrs.org/ExpressLRS/index.json';
const bundledIndexAsset = 'assets/expresslrs_index.json';
const _lastGoodKey = 'expresslrs_index_last_good';

/// Persists the last index that passed the health check.
abstract class ReleaseIndexStore {
  Future<String?> load();
  Future<void> save(String json);
}

class SharedPrefsReleaseIndexStore implements ReleaseIndexStore {
  @override
  Future<String?> load() async =>
      (await SharedPreferences.getInstance()).getString(_lastGoodKey);

  @override
  Future<void> save(String json) async =>
      (await SharedPreferences.getInstance()).setString(_lastGoodKey, json);
}

/// Resolves the ExpressLRS release tags (version -> commit hash).
///
/// The Artifactory index is regenerated by upstream CI and has been published
/// empty (2026-11-27) while every firmware.zip stayed downloadable. So a live
/// index that is empty or has lost more than half the known tags is treated
/// as degraded: the last good copy (saved on device, else bundled with the
/// app) is used instead, with any tags the live index does have merged in.
/// A healthy live index always wins, so upstream removals are honoured.
class ReleaseIndexRepository {
  ReleaseIndexRepository({
    required this._fetchLive,
    required this._store,
    Future<String> Function()? loadBundled,
  })  : _loadBundled =
            loadBundled ?? (() => rootBundle.loadString(bundledIndexAsset));

  final Future<Object?> Function() _fetchLive;
  final ReleaseIndexStore _store;
  final Future<String> Function() _loadBundled;

  /// Network failures are rethrown so callers keep their offline handling.
  Future<Map<String, String>> fetchTags() async {
    final live = parseTags(await _fetchLive());
    final fallback = await _loadFallback();

    if (isHealthy(live, fallback)) {
      await _store.save(jsonEncode({'tags': live}));
      return live;
    }

    _log.warning(
      'Artifactory index looks degraded (${live.length} tags vs '
      '${fallback.length} last known good). Using last known good index.',
    );
    return {...fallback, ...live};
  }

  static bool isHealthy(Map<String, String> live, Map<String, String> fallback) {
    if (live.isEmpty) return false;
    return live.length * 2 >= fallback.length;
  }

  /// Accepts a decoded JSON map or a raw JSON string; anything malformed
  /// yields an empty map (and is therefore treated as degraded).
  static Map<String, String> parseTags(Object? data) {
    try {
      final decoded = data is String ? jsonDecode(data) : data;
      if (decoded is! Map) return {};
      final tags = decoded['tags'];
      if (tags is! Map) return {};
      return {
        for (final e in tags.entries)
          if (e.key is String && e.value is String && (e.value as String).isNotEmpty)
            e.key as String: e.value as String,
      };
    } catch (_) {
      return {};
    }
  }

  Future<Map<String, String>> _loadFallback() async {
    try {
      final saved = parseTags(await _store.load());
      if (saved.isNotEmpty) return saved;
    } catch (e) {
      _log.warning('Could not read saved index: $e');
    }
    try {
      return parseTags(await _loadBundled());
    } catch (e) {
      _log.warning('Could not read bundled index: $e');
      return {};
    }
  }
}

@riverpod
ReleaseIndexRepository releaseIndexRepository(Ref ref) {
  final dio = ref.watch(internetDioProvider);
  // Captured eagerly: callers often hold this repository past the provider's
  // auto-dispose (e.g. across awaits), so fetchLive must not touch `ref`.
  final connectivity = ref.read(connectivityServiceProvider.notifier);
  return ReleaseIndexRepository(
    fetchLive: () async {
      final response = await connectivity
          .withInternetAccess(() => dio.get(artifactoryIndexUrl));
      return response.data;
    },
    store: SharedPrefsReleaseIndexStore(),
  );
}
